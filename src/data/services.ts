/* ───────────────────────── Помощники ───────────────────────── */

export function getCategory(slug: string) {
  return categories.find((c) => c.slug === slug);
}

export function getService(category: string, slug: string) {
  return services.find((s) => s.category === category && s.slug === slug);
}

export function servicesOf(category: CategorySlug) {
  return services.filter((s) => s.category === category);
}

export function serviceHref(s: Service) {
  return s.page ? `/uslugi/${s.category}/${s.slug}` : `/uslugi/${s.category}#${s.slug}`;
}

export function categoryHref(c: Category | CategorySlug) {
  return `/uslugi/${typeof c === "string" ? c : c.slug}`;
}

export function formatPrice(value: number) {
  return `${value.toLocaleString("ru-RU")} ₸`;
}

/** Изображение для страницы услуги: своё либо изображение категории */
export function serviceImage(s: Service) {
  if (s.image) return { src: s.image, alt: s.imageAlt ?? s.title, position: s.imagePosition };
  const c = getCategory(s.category);
  if (c?.image) return { src: c.image, alt: c.imageAlt ?? c.title, position: c.imagePosition };
  return null;
}

